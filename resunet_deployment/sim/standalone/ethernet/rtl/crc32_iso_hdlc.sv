//========================================================================================
// 文件类型: .sv
// 模块功能: CRC-32/ISO-HDLC 字节流水位宽校验引擎 (协议帧 CRC 字段专用)
//
// 微架构:
//   - 标准反射实现: Poly 0xEDB88320, Init 0xFFFFFFFF, XorOut 0xFFFFFFFF
//   - 逐字节更新, 单周期出一个字节的迭代结果, 无空泡
//   - crc_data 输出为"已完成最终异或"的值, 即与 PC 端 zlib.crc32 逐位相同
//
// 设计说明 (为何不复用例程 arp/crc32_d8.v):
//   例程 crc32_d8.v 实现的是"以太网 FCS"约定: 它对输入字节做位反转(data_t),
//   其 crc_data 与本模块结果满足 crc32_d8 = bitreverse32(~crc_iso_hdlc)。
//   实测: 输入 "123456789" -> crc32_d8=0x9B63D02C, ~后=0x649C2FD3,
//   而 zlib.crc32=0xCBF43926 = bitreverse32(0x649C2FD3)。
//   协议帧的 CRC32 字段要求等于 zlib.crc32, 故必须使用本模块;
//   crc32_d8.v 仍正确用于以太网 FCS 发送(udp_tx), 两者不可混用。
//========================================================================================

module crc32_iso_hdlc (
    input  logic        clk_i      ,  // 时钟
    input  logic        rst_n_i    ,  // 复位, 低有效

    input  logic        crc_init_i ,  // 1: 复位 CRC 到 0xFFFFFFFF (帧起始)
    input  logic        crc_en_i   ,  // 1: 本拍吃入 data_i 一个字节

    input  logic [7:0]  data_i     ,  // 待校验字节
    output logic [31:0] crc_o         // 已完成 XorOut 的 CRC 值
);

//========================================================================================
// CRC 寄存器
//========================================================================================
logic [31:0] crc_r;
logic [31:0] crc_nxt;

//========================================================================================
// 组合: 单字节迭代 (反射, LSB first)
//========================================================================================
always_comb begin
    logic [31:0] x;

    x = crc_r ^ {24'd0, data_i};

    for (int i = 0; i < 8; i++) begin
        x = x[0] ? ((x >> 1) ^ 32'hEDB8_8320) : (x >> 1);
    end

    crc_nxt = x;
end

//========================================================================================
// 时序: 更新
//========================================================================================
always_ff @(posedge clk_i or negedge rst_n_i) begin
    if (!rst_n_i)
        crc_r <= 32'hFFFF_FFFF;
    else if (crc_init_i)
        crc_r <= 32'hFFFF_FFFF;
    else if (crc_en_i)
        crc_r <= crc_nxt;
end

//========================================================================================
// 输出: 最终异或
//========================================================================================
assign crc_o = ~crc_r;

endmodule
